uint8_t OV2640_ImageWin_Set(uint16_t offx, uint16_t offy, uint16_t width, uint16_t height) {
    uint16_t hsize = width / 4;
    uint16_t vsize = height / 4;
    uint8_t temp; 
    
    if(width % 4) return 1;
    if(height % 4) return 2;
    
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xFF, 0x00);	
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xE0, 0x04);					
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x51, hsize & 0xFF);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x52, vsize & 0xFF);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x53, offx & 0xFF);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x54, offy & 0xFF);
    
    temp = (vsize >> 1) & 0x80;
    temp |= (offy >> 4) & 0x70;
    temp |= (hsize >> 5) & 0x08;
    temp |= (offx >> 8) & 0x07; 
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x55, temp);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x57, (hsize >> 2) & 0x80);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xE0, 0x00);	
    return 0;
}

uint8_t OV2640_OutSize_Set(uint16_t width, uint16_t height) {
    uint16_t outh, outw;
    uint8_t temp; 
    
    if(width % 4) return 1;
    if(height % 4) return 2;
    
    outw = width / 4;
    outh = height / 4; 
    
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xFF, 0x00);	
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xE0, 0x04);			
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x5A, outw & 0xFF);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x5B, outh & 0xFF);
    
    temp = (outw >> 8) & 0x03;
    temp |= (outh >> 6) & 0x04;
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0x5C, temp);
    rawSccbWriteReg(OV2640_SCCB_ADDR, 0xE0, 0x00);	
    return 0;
}
